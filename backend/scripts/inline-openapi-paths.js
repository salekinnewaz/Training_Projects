/**
 * Build-time codegen for the OpenAPI `paths` block.
 *
 * Runs swagger-jsdoc at prebuild time (when `process.cwd()` is
 * the backend workspace and the apis glob `./src/routes/*.ts`
 * resolves correctly) and writes the resulting `paths` object
 * to `backend/src/docs/openapi.paths.ts` as an exported
 * `INLINED_OPENAPI_PATHS` constant. The runtime openapi.ts
 * imports that constant instead of calling swagger-jsdoc itself.
 *
 * **Why this exists.** The OpenAPI spec is assembled by scanning
 * every `@openapi` JSDoc block in the controllers. swagger-jsdoc
 * resolves the `apis` glob at runtime, relative to
 * `process.cwd()`. In `tsx watch` dev that's `backend/`, so the
 * glob matches and the spec is correct. On Vercel Functions
 * `process.cwd()` is `/var/task/` — the Function root — and
 * `./src/routes/*.ts` resolves to nothing. swagger-jsdoc happily
 * returns a spec with `paths: {}`, and the Swagger UI page
 * shows the tag list (which lives in our hand-written
 * `definition.tags` array) but no operations under any tag
 * (because `paths` is empty). The unit test didn't catch this
 * because it runs from `backend/`, where the glob works.
 *
 * Running the scan at build time — when the source tree is
 * actually present and `cwd` is correct — produces a static
 * `paths` object that gets compiled into the Function bundle
 * and is therefore available at request time regardless of
 * what `cwd` happens to be on the server.
 *
 * Trade-offs:
 *   - Re-running the script on every build is mandatory, so the
 *     `paths` object stays in sync with the latest JSDoc. We
 *     wire it into the backend's `prebuild` npm script (the
 *     same hook that already runs the assets inliner). On a
 *     cold checkout, `npm run build` produces a correct spec
 *     without any extra step.
 *   - The generated `openapi.paths.ts` is committed to the repo
 *     so the build is hermetic and reviewers see the data. The
 *     script is idempotent — re-run any time a controller
 *     @openapi block changes.
 *
 * Invocation: `node backend/scripts/inline-openapi-paths.js`
 */
'use strict';

const fs = require('fs');
const path = require('path');
const swaggerJSDoc = require('swagger-jsdoc');

// swagger-jsdoc resolves the `apis` glob against `process.cwd()`,
// which is whoever invoked the script — `backend/` when run as
// `npm run prebuild`, the repo root when run as
// `node backend/scripts/inline-openapi-paths.js`, and `/var/task/`
// on Vercel. The behaviour must be the same in all three.
//
// The simplest portable answer: cd into a known directory before
// invoking swagger-jsdoc. We use the directory containing this
// script (`backend/scripts/`) and the apis globs are written as
// relative to the backend root.
process.chdir(path.resolve(__dirname, '..'));

const swaggerOptions = {
  definition: {
    openapi: '3.0.3',
    // The other top-level fields (info / components / tags /
    // servers) are not used by swagger-jsdoc when scanning
    // JSDoc — only `paths` is built from the comments. We pass
    // them anyway to keep the option object shaped like the
    // one in `openapi.ts` so the two stay in lockstep.
    info: { title: 'placeholder', version: '0.0.0' },
  },
  apis: [
    './src/routes/*.ts',
    './src/controllers/*.ts',
  ],
};

const scanned = swaggerJSDoc(swaggerOptions);
const paths = scanned.paths || {};
const pathCount = Object.keys(paths).length;

if (pathCount === 0) {
  // Loud failure: an empty `paths` is the exact symptom we
  // wrote this script to prevent. Bail out so the build fails
  // rather than shipping a silently-broken spec.
  console.error(
    '[inline-openapi-paths] swagger-jsdoc returned 0 paths. ' +
      'The apis glob likely failed to match. cwd=' + process.cwd() +
      ' apis=' + JSON.stringify(swaggerOptions.apis),
  );
  process.exit(1);
}

const out = `/**
 * AUTO-GENERATED by backend/scripts/inline-openapi-paths.js.
 * Do not edit by hand — re-run the script to regenerate.
 *
 * The OpenAPI \`paths\` object produced by scanning every
 * \`@openapi\` JSDoc block in src/routes/*.ts and
 * src/controllers/*.ts. Computed at build time (so the apis
 * glob resolves correctly) and embedded as a static object
 * here so the compiled Function bundle contains it — the
 * source .ts files are not in the Vercel deployment payload,
 * and a runtime swagger-jsdoc call against
 * \`process.cwd()\` on the Function would return an empty
 * spec.
 *
 * See backend/scripts/inline-openapi-paths.js for the full
 * rationale.
 */
export const INLINED_OPENAPI_PATHS: Record<string, Record<string, unknown>> = ${JSON.stringify(paths, null, 2)};
`;

// Write next to the consuming module so the import path is short.
const outDir = path.resolve(__dirname, '..', 'src', 'docs');
const outFile = path.join(outDir, 'openapi.paths.ts');
fs.writeFileSync(outFile, out, 'utf8');

console.log(
  `[inline-openapi-paths] wrote ${pathCount} paths ` +
    `(${(out.length / 1024).toFixed(1)} KB) ` +
    `to ${path.relative(process.cwd(), outFile)}`,
);
